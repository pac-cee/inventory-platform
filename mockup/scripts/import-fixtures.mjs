// Turns the app's own mock data (src/lib/api/mock/fixtures.json) into the
// mockup's data module, so people, locations, items, stock, the ledger and
// payments match what the Next.js app shows in mock mode.
//   node scripts/import-fixtures.mjs   (run from mockup/)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const src = here("../../src/lib/api/mock/fixtures.json");
const { capturedAt, responses: r } = JSON.parse(readFileSync(src, "utf8"));

const items = (Array.isArray(r["/items?limit=200&offset=0"]) ? r["/items?limit=200&offset=0"] : r["/items?limit=200&offset=0"].items)
  .map((i) => ({ id: i.id, sku: i.sku, type: i.type, name: i.name, model: i.model || "", spec: i.specification || "", category: i.category || null, finishable: !!i.finishable }));

const locations = r["/locations"].map((l) => ({ id: l.id, name: l.name, parent_id: l.parent_id, kind: l.kind, label: l.label || null }));

const stock = r["/stock"].map((s) => ({ item_id: s.item_id, location_id: s.location_id, quantity: s.quantity, damaged: s.damaged, capacity: s.capacity }));

const people = r["/profiles"].map((p) => ({
  id: p.id, name: p.full_name, role: p.role, cashier: p.fallback_role === "cashier",
  pay: !!p.has_payment_permission, manage: !!p.can_manage_inventory,
  daily: p.daily_limit, monthly: p.monthly_limit, perTxn: p.per_transaction_limit,
}));

const b = r["/payments/budgets"];
const budget = { year: b.year, month: b.month, allocated: b.allocated_amount, remaining: b.remaining_amount };

const STATUS = { pending: "pending", completed: "successful", successful: "successful", failed: "rejected", rejected: "rejected" };
const payments = r["/payments/transactions?limit=100"].map((t) => ({
  id: t.id, user_id: t.user_id, amount: t.amount, momo: t.recipient_phone, status: STATUS[t.status] || t.status,
  note: t.failure_reason || null, at: Date.parse(t.created_at),
  purpose: (t.transaction_products || []).map((p) => `${p.name}${p.quantity > 1 ? ` × ${p.quantity}` : ""}`).join(", ") || "Expense",
  location: t.locations?.name || null,
}));

const reasons = { initial: "initial", take: "take", return: "return", damaged: "damaged", destroyed: "damaged", lost: "lost", repaired: "repair", repair: "repair", finish: "finish" };
const report = r["/movements/report?from=2026-08-11&limit=500"];
const movements = report.rows.map((m) => ({
  item_id: m.item.id, location_id: m.location.id, kind: reasons[m.reason] || m.reason,
  delta: m.delta, damaged_delta: m.damaged_delta || 0, person_id: m.person?.id || null,
  actor_id: m.actor?.id || null, note: m.note || "", at: Date.parse(m.created_at), reversed: !!m.reversed,
})).sort((a, b) => a.at - b.at);

const out = `// Generated by scripts/import-fixtures.mjs from src/lib/api/mock/fixtures.json
// (captured ${capturedAt}). Do not edit by hand; re-run the script.
export const CAPTURED_AT = ${JSON.stringify(capturedAt)};
export const ITEMS = ${JSON.stringify(items, null, 0)};
export const LOCATIONS = ${JSON.stringify(locations, null, 0)};
export const STOCK = ${JSON.stringify(stock, null, 0)};
export const PEOPLE = ${JSON.stringify(people, null, 0)};
export const BUDGET = ${JSON.stringify(budget)};
export const PAYMENTS = ${JSON.stringify(payments, null, 0)};
export const MOVEMENTS = ${JSON.stringify(movements, null, 0)};
`;
writeFileSync(here("../src/fixtures.js"), out.replace(/\},\{/g, "},\n  {"));
console.log(`fixtures.js: ${items.length} items, ${locations.length} locations, ${stock.length} stock rows, ${people.length} people, ${payments.length} payments, ${movements.length} movements`);
console.log("reasons seen:", [...new Set(report.rows.map((m) => m.reason))].join(", "));
